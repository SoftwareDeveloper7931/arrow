  /// Returns the canonical shape mask for [levelNumber] (1-indexed).
  /// Level 1 is always Trophy.
  static ShapeMask getShapeForLevel(int levelNumber) {
    final index = (levelNumber - 1) % _catalog.length;
    return _catalog[index];
  }

  /// Procedural shape generator for circles.
  static ShapeMask createProceduralCircle(int size) {
    final r = size / 2.0;
    final grid = List.generate(size, (y) {
      return List.generate(size, (x) {
        final dx = x - r + 0.5;
        final dy = y - r + 0.5;
        return (dx * dx + dy * dy) <= (r * r * 0.85);
      });
    });
    return ShapeMask(name: 'Circle', width: size, height: size, grid: grid);
  }
